const MobileScroll = ({ src, title }) => {
  const containerRef = useRef(null);
  const { scrollYProgress } = useScroll({
    target: containerRef,
    offset: ["start start", "end start"]
  });

  useEffect(() => {
    // Disable auto-scroll for mobile to prevent infinite loop
    // The scroll animations are handled by Framer Motion transforms
    return () => { };
  }, []);

  const rotate = useTransform(scrollYProgress, [0, 0.1, 0.3], [-25, -25, 0]);
  const scale = useTransform(scrollYProgress, [0, 0.7], [0.5, 1.5]);
  const translateY = useTransform(scrollYProgress, [0, 1], [0, 1500]);
  const textOpacity = useTransform(scrollYProgress, [0, 0.2], [1, 0]);
  const phoneOpacity = useTransform(scrollYProgress, [0.6, 0.75], [1, 0]);



  return (
    <div className="relative min-h-[200vh]" ref={containerRef}>
      <div className="sticky top-0 left-0 w-full h-screen flex items-center justify-center">
        <motion.div style={{ opacity: textOpacity }} className="absolute top-20 left-1/2 -translate-x-1/2 w-full text-center z-10">
          <h2 className="text-2xl font-bold text-neutral-800 dark:text-white">
            {title || "Scroll Animation"}
          </h2>
        </motion.div>
        <div style={{ perspective: "1000px" }} className="w-full max-w-xs">
          <motion.div
            style={{
              scale,
              rotateX: rotate,
              translateY,
              opacity: phoneOpacity,
              transformStyle: "preserve-3d",
              transformOrigin: "center center"
            }}>
            <Iphone videoSrc={src} />
          </motion.div>
        </div>
      </div>
    </div>
  );
};




export const MacbookScroll = ({
  src,
  showGradient,
  title,
  badge
}) => {
  const ref = useRef(null);
  const { scrollYProgress } = useScroll({
    target: ref,
    offset: ["start start", "end start"],
  });

  const [isMobile, setIsMobile] = useState(false);
  const [isXl, setIsXl] = useState(false);

  useEffect(() => {
    const checkScreenSize = () => {
      // Use natural viewport detection with higher threshold for stability
      const vw = Math.max(document.documentElement.clientWidth || 0, window.innerWidth || 0);
      setIsMobile(vw < 768);
      setIsXl(vw >= 1280);
    };

    // Initial check with delay to ensure DOM is ready
    const initialTimeout = setTimeout(checkScreenSize, 100);

    // Improved debouncing with longer delay to prevent rapid changes
    let resizeTimeout;
    const debouncedResize = () => {
      clearTimeout(resizeTimeout);
      resizeTimeout = setTimeout(checkScreenSize, 300); // Increased from 150ms
    };

    // Orientation change with longer delay for device rotation
    let orientationTimeout;
    const handleOrientationChange = () => {
      clearTimeout(orientationTimeout);
      orientationTimeout = setTimeout(checkScreenSize, 800); // Increased from 500ms
    };

    window.addEventListener('resize', debouncedResize, { passive: true });
    window.addEventListener('orientationchange', handleOrientationChange, { passive: true });

    return () => {
      clearTimeout(initialTimeout);
      clearTimeout(resizeTimeout);
      clearTimeout(orientationTimeout);
      window.removeEventListener('resize', debouncedResize);
      window.removeEventListener('orientationchange', handleOrientationChange);
    };
  }, []);

  useEffect(() => {
    if (isMobile) return;

    // Disable auto-scroll behavior to prevent infinite loop
    // The scroll animations are handled by Framer Motion useScroll and useTransform
    // This prevents the component from hijacking natural scroll behavior

    let scrollTimeout;
    let lastScroll = window.scrollY;

    // Debounced scroll handler for performance optimization only
    const handleScroll = () => {
      clearTimeout(scrollTimeout);
      scrollTimeout = setTimeout(() => {
        lastScroll = window.scrollY;
      }, 16); // ~60fps throttling
    };

    window.addEventListener('scroll', handleScroll, { passive: true });
    return () => {
      window.removeEventListener('scroll', handleScroll);
      clearTimeout(scrollTimeout);
    };
  }, [isMobile]);

  const scaleX = useTransform(scrollYProgress, [0, 1], [1.2, isMobile ? 3.0 : isXl ? 5.5 : 4.8]);
  const scaleY = useTransform(scrollYProgress, [0, 1], [0.6, isMobile ? 2.0 : 3.2]);

  const translate = useTransform(scrollYProgress, [0, 1], [0, 2500]);
  const rotate = useTransform(scrollYProgress, [0.1, 0.12, 0.3], [-28, -28, 0]);
  const textTransform = useTransform(scrollYProgress, [0, 0.3], [0, 100]);
  const textOpacity = useTransform(scrollYProgress, [0, 0.2], [1, 0]);
  const lidOpacity = useTransform(scrollYProgress, [0.8, 1], [1, 0]);

  if (isMobile) {
    return <MobileScroll src="https://res.cloudinary.com/dgpzvkjki/video/upload/v1760972230/Mobile_view_iwhclu.mp4" title={title} />;
  }

  return (
    <div
      ref={ref}
      className="relative flex min-h-[200vh] w-full max-w-full shrink-0 scale-[0.35] transform flex-col items-center justify-start overflow-hidden py-0 [perspective:800px] sm:scale-50 md:scale-100 md:py-40">
      <motion.h2
        style={{
          translateY: textTransform,
          opacity: textOpacity,
        }}
        className="mb-20 text-center text-3xl font-bold text-neutral-800 dark:text-white">
        {title || (
          <span>
            {/* This Macbook is built with Tailwindcss. <br /> No kidding. */}
          </span>
        )}
      </motion.h2>
      <Lid
        src={src}
        scaleX={scaleX}
        scaleY={scaleY}
        rotate={rotate}
        translate={translate}
        lidOpacity={lidOpacity}
      />
      <div className="relative -z-10 h-[22rem] w-[32rem] overflow-hidden rounded-2xl bg-gray-200 dark:bg-[#272729]">
        <div className="relative h-10 w-full">
          <div className="absolute inset-x-0 mx-auto h-4 w-[80%] bg-[#050505]" />
        </div>
        <div className="relative flex">
          <div className="mx-auto h-full w-[10%] overflow-hidden">
            <SpeakerGrid />
          </div>
          <div className="mx-auto h-full w-[80%]">
            <Keypad />
          </div>
          <div className="mx-auto h-full w-[10%] overflow-hidden">
            <SpeakerGrid />
          </div>
        </div>
        <Trackpad />
        <div className="absolute inset-x-0 bottom-0 mx-auto h-2 w-20 rounded-tl-3xl rounded-tr-3xl bg-gradient-to-t from-[#272729] to-[#050505]" />
        {showGradient && (
          <div className="absolute inset-x-0 bottom-0 z-50 h-40 w-full bg-gradient-to-t from-white via-white to-transparent dark:from-black dark:via-black"></div>
        )}
        {badge && <div className="absolute bottom-4 left-4">{badge}</div>}
      </div>
    </div>
  );
};

